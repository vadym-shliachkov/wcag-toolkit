// Decorative: every icon sits next to its text label, so it is hidden from the PDF structure.
export function groupIcon(id, cls = 'gicon') {
  const body = PATHS[id];
  if (!body) return '';
  return `<svg class="${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
}

// Severity as a 4-bar signal meter: reads in greyscale and needs no legend beside its word.
const LEVEL = { critical: 4, serious: 3, moderate: 2, minor: 1 };
export function sevGlyph(sev) {
  const n = LEVEL[sev] ?? 0;
  const bars = [0, 1, 2, 3].map((i) => {
    const h = 4 + i * 3;
    return `<rect x="${i * 5}" y="${14 - h}" width="3.4" height="${h}" rx="0.8" class="${i < n ? 'on' : 'off'}"/>`;
  }).join('');
  return `<svg class="sev-glyph" viewBox="0 0 19 14" aria-hidden="true" focusable="false">${bars}</svg>`;
}
